// Regenerates the light crop index and the lazy loaders from lib/crops/data/*.ts.
//   npm run crops:index
// Run it after adding or editing a crop file; `npm run check:crops` fails if they are out of date.
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import type { CropInfo } from "../lib/types.ts";
import { indexEntryOf } from "../lib/crops/index-entry.ts";

const DATA = join(import.meta.dirname, "..", "lib", "crops", "data");

export async function loadAllCropFiles(): Promise<{ file: string; crop: CropInfo }[]> {
  const files = readdirSync(DATA).filter((f) => f.endsWith(".ts")).sort();
  const out: { file: string; crop: CropInfo }[] = [];
  for (const file of files) {
    const mod = (await import(pathToFileURL(join(DATA, file)).href)) as { default: CropInfo };
    out.push({ file, crop: mod.default });
  }
  return out;
}

async function main() {
  const all = await loadAllCropFiles();
  const entries = all.map(({ crop }) => indexEntryOf(crop)).sort((a, b) => a.id.localeCompare(b.id));
  const header = "// GENERATED by scripts/gen-crop-index.ts — do not edit. Run `npm run crops:index`.\n";
  writeFileSync(
    join(DATA, "..", "index.generated.ts"),
    `${header}import type { CropIndexEntry } from "./index-entry.ts";\n\nexport const CROP_INDEX: CropIndexEntry[] = ${JSON.stringify(entries, null, 1)};\n`,
  );
  writeFileSync(
    join(DATA, "..", "loaders.generated.ts"),
    `${header}import type { CropInfo } from "../types";\n\n/** Static paths so the bundler splits every crop into its own chunk. */\nexport const LOADERS: Record<string, () => Promise<{ default: CropInfo }>> = {\n${all
      .map(({ file }) => `  ${JSON.stringify(file.replace(/\.ts$/, ""))}: () => import("./data/${file.replace(/\.ts$/, "")}"),`)
      .join("\n")}\n};\n`,
  );
  console.log(`✓ ${entries.length} crops indexed`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) await main();
